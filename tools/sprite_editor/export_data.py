#!/usr/bin/env python3
"""Export a few species (game sprite + packed planes) as data.js for the web prototype.

  python3.11 tools/sprite_editor/export_data.py --pack output/stereo-full-detail/complete-mons.bin \
      --graphics build/upstream/graphics/pokemon --root build/upstream 25 150 6 94 384 1

Each species: 16-colour palette, two 64x64 frames of colour indices (hex string,
0 = transparent) and two 64x64 frames of plane numbers (hex string, f = none).
"""
import argparse, json, os, struct, sys
from PIL import Image

def dex_names(root):
    names, inside = {}, False
    with open(os.path.join(root, "include", "constants", "pokedex.h")) as f:
        for line in f:
            s = line.strip()
            if s == "NATIONAL_DEX_NONE,":
                inside = True; continue
            if inside:
                if s.startswith("}"): break
                if s.startswith("NATIONAL_DEX_") and s.endswith(","):
                    names[len(names) + 1] = s[len("NATIONAL_DEX_"):-1].lower()
    return names

ap = argparse.ArgumentParser()
ap.add_argument("--pack", required=True); ap.add_argument("--graphics", required=True)
ap.add_argument("--root", required=True); ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "data.js"))
ap.add_argument("dex", nargs="+", type=int)
a = ap.parse_args()
names = dex_names(a.root)
blob = open(a.pack, "rb").read()
magic, count, planes, frames, w, h = struct.unpack_from("<8sHBBHH", blob)
assert magic == b"EM3DSTM1" and (w, h) == (64, 64)
index = {}
for i in range(count):
    dex, _, off = struct.unpack_from("<HHI", blob, 16 + 8 * i)
    index[dex] = off
out = []
for dex in a.dex:
    name = names[dex]
    im = Image.open(os.path.join(a.graphics, name, "anim_front.png"))
    assert im.mode == "P" and im.size == (64, 128), (name, im.mode, im.size)
    pal = im.getpalette()[:48]
    palette = ["#%02x%02x%02x" % tuple(pal[i*3:i*3+3]) for i in range(16)]
    idx = list(im.getdata())
    color_frames = ["".join("%x" % idx[(y + f*64)*64 + x] for y in range(64) for x in range(64)) for f in range(2)]
    plane_frames = []
    if dex in index:
        off = index[dex]
        for f in range(frames):
            fb = blob[off + f*2048: off + (f+1)*2048]
            s = []
            for b in fb:
                s.append("%x" % (b & 15)); s.append("%x" % (b >> 4))
            plane_frames.append("".join(s))
    else:
        plane_frames = ["f" * 4096] * 2
    out.append({"dex": dex, "name": name, "palette": palette, "colors": color_frames, "planes": plane_frames})
    print(name, "planes" if dex in index else "NO PLANES")
with open(a.out, "w") as f:
    f.write("// Generated by export_data.py - real Emerald sprites + packed stereo planes.\n")
    f.write("window.SPRITE_DATA = " + json.dumps({"planes": planes, "species": out}) + ";\n")
print("wrote", a.out)
