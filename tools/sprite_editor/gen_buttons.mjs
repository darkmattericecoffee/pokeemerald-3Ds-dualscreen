// Usage: node gen_buttons.mjs <out header> [<Buttons Full Solid/White/SVG dir>]; needs @resvg/resvg-js (see gen_icons.mjs).
// The chosen look (V5: Zacksly's "Buttons Full Solid", CC BY 3.0, a 1 px shadow at 25%) at the
// 3DS top screen's scale, into a C header of 1-byte pixels: 0 none, 1 ink, 2 shadow, 3 dark.
import { Resvg } from '/private/tmp/claude-501/-Users-arnoud-coding-local-pokeemerald-3Ds-dualscreen/d8dd672c-f0f7-4822-a52d-e540bf4a34c4/scratchpad/icons2/node_modules/@resvg/resvg-js/index.js';
import fs from 'node:fs';
const DIR = process.argv[3] || '/Users/arnoud/Downloads/Switch Button Icons and Controls/Buttons Full Solid/White/SVG';
const SCALE = 20 / 340, SHADOW = 0.25;
const SET = [
  ['BTN_A', ['A']], ['BTN_B', ['B']], ['BTN_X', ['X']], ['BTN_Y', ['Y']], ['BTN_L', ['L']], ['BTN_R', ['R']],
  ['BTN_L_SMALL', ['L'], 0.75], ['BTN_DPAD_UD', ['Pro D-Pad Up', 'Pro D-Pad Down']], ['BTN_DPAD_LR', ['Pro D-Pad Left', 'Pro D-Pad Right']],
  ['BTN_PAD', ['Left Stick All'], 0.8], ['BTN_CSTICK', ['@button_cstick.svg'], 0.8], ['BTN_START', ['Plus']], ['BTN_SELECT', ['Minus']],
];
function render(svg, scale) { const i = new Resvg(svg, { fitTo: { mode: 'zoom', value: scale } }).render(); return { w: i.width, h: i.height, px: i.pixels }; }
function bbox(svg) {
  const { w, h, px } = render(svg, 0.25); let x0 = w, y0 = h, x1 = -1, y1 = -1;
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) if (px[(y * w + x) * 4 + 3] > 8) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  return { x0: x0 * 4, y0: y0 * 4, x1: x1 * 4 + 3, y1: y1 * 4 + 3 };
}
function prepare(svg, box, scale) {
  const m = 2 / scale, u = 1 / scale;
  let s = svg.replace(/viewBox="[^"]*"/, `viewBox="${box.x0 - m} ${box.y0 - m} ${box.x1 - box.x0 + 2 * m} ${box.y1 - box.y0 + 2 * m}"`);
  const filter = `<filter id="sh" x="-20%" y="-20%" width="150%" height="150%" color-interpolation-filters="sRGB"><feOffset in="SourceAlpha" dx="${u}" dy="${u}" result="o"/><feFlood flood-color="#000" flood-opacity="${SHADOW}" result="f"/><feComposite in="f" in2="o" operator="in" result="s"/><feMerge><feMergeNode in="s"/><feMergeNode in="SourceGraphic"/></feMerge></filter>`;
  if (s.includes('<defs>')) s = s.replace('<defs>', '<defs>' + filter); else s = s.replace(/(<svg[^>]*>)/, `$1<defs>${filter}</defs>`);
  return s.replace(/(<\/defs>)/, '$1<g filter="url(#sh)">').replace(/<\/svg>\s*$/, '</g></svg>');
}
// The D-pad: the plain white cross with its own four small arrows covered in white (the white arrows
// of the single-arm icons, all four between two of them), and a larger black arrow on each of the two
// arms meant: up and down, or left and right.
function dpad(upDown) {
  const cross = fs.readFileSync(`${DIR}/Pro D-Pad.svg`, 'utf8');
  const covers = ['Up', 'Left'].flatMap(arm =>
    [...fs.readFileSync(`${DIR}/Pro D-Pad ${arm}.svg`, 'utf8').matchAll(/<path class="cls-2" d="[^"]*"\/>/g)]
      .map(m => m[0].replace('class="cls-2"', 'fill="#fff" stroke="#fff" stroke-width="8"')));
  const arrows = upDown
    ? ['M256,100 l-40,56 h80 z', 'M256,412 l-40,-56 h80 z']
    : ['M100,256 l56,-40 v80 z', 'M412,256 l-56,-40 v80 z'];
  return cross.replace(/<\/svg>\s*$/, covers.join('') + arrows.map(d => `<path d="${d}" fill="#000"/>`).join('') + '</svg>');
}
const icons = [];
for (const [name, files, zoom = 1] of SET) {
  const scale = SCALE * zoom;
  const svgs = name.startsWith('BTN_DPAD') ? [dpad(name === 'BTN_DPAD_UD')]
    : files.map(f => fs.readFileSync(f.startsWith('@') ? new URL(f.slice(1), import.meta.url) : `${DIR}/${f}.svg`, 'utf8'));
  // One box for the pair (the cross is the same in both), so they line up.
  const b = bbox(svgs[0]);
  let out = null;
  for (const svg of svgs) {
    const { w, h, px } = render(prepare(svg, b, scale), scale);
    if (!out) out = { w, h, codes: new Uint8Array(w * h) };
    for (let i = 0; i < w * h; i++) {
      const a = px[i * 4 + 3], lum = px[i * 4];
      // 1 the white, 2 the shadow (faint), 3 black drawn on the icon (the D-pad's arrows).
      const code = a < 60 ? 0 : lum > 127 ? 1 : a > 200 ? 3 : 2;
      if (code > out.codes[i] || (code === 1)) out.codes[i] = Math.max(out.codes[i], code);
      if (code === 1) out.codes[i] = 1;
    }
  }
  icons.push({ name, ...out });
}
let h = '/* Generated by tools/sprite_editor/gen_buttons.mjs from "Switch Button Icons and Controls" by Zacksly\n' +
  ' * (https://zacksly.itch.io, CC BY 3.0; the Full Solid set, modified: cropped, a pixel shadow added, the\n' +
  ' * D-pad pairs merged, a C-stick made from a stick): do not edit. A byte a pixel: 0 none, 1 ink, 2 shadow, 3 dark. */\n' +
  '#ifndef CTR_BUTTON_ICONS_H\n#define CTR_BUTTON_ICONS_H\n#include <stdint.h>\n' +
  'enum { ' + icons.map(i => i.name).join(', ') + ', BTN_TOUCH, BTN_COUNT };\n' +
  'typedef struct { uint8_t w, h; uint16_t offset; } CtrButtonIcon;\n';
let data = [], table = [];
for (const i of icons) { table.push(`    {${i.w}, ${i.h}, ${data.length}}, /* ${i.name} */`); data.push(...i.codes); }
h += `static const CtrButtonIcon sButtonIcons[BTN_COUNT] = {\n${table.join('\n')}\n    {0, 0, 0}, /* BTN_TOUCH: drawn */\n};\n`;
h += `static const uint8_t sButtonPixels[${data.length}] = {\n`;
for (let i = 0; i < data.length; i += 40) h += '    ' + Array.from(data.slice(i, i + 40)).join(',') + ',\n';
h += '};\n#endif\n';
fs.writeFileSync(process.argv[2], h);

