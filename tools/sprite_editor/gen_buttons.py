#!/usr/bin/env python3
"""Generates 3ds_port/src/3ds_button_sprites.h: the top screen's pictures of
the console's buttons, drawn by hand as 24x24 PNGs in
tools/sprite_editor/buttons/ (the author's own).

    python3 tools/sprite_editor/gen_buttons.py

Each pixel becomes RGBA5551 as the 3DS's textures take it (r5 g5 b5 a1);
a pixel with alpha under 128 is clear. Standard library only.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "3ds_port", "src", "3ds_button_sprites.h")
SIZE = 24
# Enum name, file: in the order the header lists them.
BUTTONS = [
    ("BTN_B", "btn_b"), ("BTN_X", "btn_x"), ("BTN_Y", "btn_y"), ("BTN_START", "btn_plus"),
    ("BTN_L", "shoulder_l"), ("BTN_R", "shoulder_r"), ("BTN_L_SMALL", "shoulder_l_hold"),
    ("BTN_DPAD_UD", "dpad_updown"), ("BTN_DPAD_LR", "dpad_leftright"), ("BTN_PAD", "circle_pad"),
    ("BTN_CSTICK", "c_stick"),
]

sys.path.insert(0, HERE)
from gen_sprites import load_png  # noqa: E402


def main():
    out = [
        "/* Generated by tools/sprite_editor/gen_buttons.py from the PNGs in tools/sprite_editor/buttons: do not edit. */",
        "#ifndef CTR_BUTTON_SPRITES_H",
        "#define CTR_BUTTON_SPRITES_H",
        "#include <stdint.h>",
        f"#define BTN_SIZE {SIZE}",
        "enum { " + ", ".join(name for name, _ in BUTTONS) + ", BTN_TOUCH, BTN_COUNT };",
        "/* RGBA5551 (r5 g5 b5 a1), row by row; BTN_TOUCH is drawn. */",
        f"static const uint16_t sButtonSprites[BTN_COUNT - 1][BTN_SIZE * BTN_SIZE] = {{",
    ]
    for name, file in BUTTONS:
        w, h, rows = load_png(os.path.join(HERE, "buttons", file + ".png"))
        if (w, h) != (SIZE, SIZE):
            sys.exit(f"{file}.png is {w}x{h}, not {SIZE}x{SIZE}")
        out.append(f"    {{ /* {file} */")
        for row in rows:
            out.append("        " + ", ".join(
                f"0x{(((r >> 3) << 11) | ((g >> 3) << 6) | ((b >> 3) << 1) | 1) if a >= 128 else 0:04X}" for r, g, b, a in row) + ",")
        out.append("    },")
    out += ["};", "#endif", ""]
    open(OUT, "w").write("\n".join(out))
    print(OUT)


if __name__ == "__main__":
    main()
