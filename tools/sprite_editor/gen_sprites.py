#!/usr/bin/env python3
"""Generates 3ds_port/src/3ds_edit_sprites.h: the plane editor's colour tool
sprites (the pencil, the bucket, the hand, the magnifier), drawn by hand as
16x16 PNGs in tools/sprite_editor/sprites/.

    python3 tools/sprite_editor/gen_sprites.py

Each pixel becomes RGB565; a clear one (alpha under 128) becomes
SPRITE_CLEAR, a colour no opaque pixel is allowed to take. Standard library
only (no Pillow): the PNGs must be 8-bit RGBA, not interlaced.
"""
import os
import struct
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "3ds_port", "src", "3ds_edit_sprites.h")
SIZE = 16
CLEAR = 0xF81F
# Enum name, file: in the order the header lists them.
SPRITES = [("SPRITE_PENCIL", "pencil"), ("SPRITE_BUCKET", "bucket"), ("SPRITE_HAND", "hand"), ("SPRITE_ZOOM", "zoom"), ("SPRITE_LASSO", "lasso")]


def load_png(path):
    data = open(path, "rb").read()
    assert data[:8] == b"\x89PNG\r\n\x1a\n", path
    pos, idat = 8, b""
    while pos + 8 <= len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        pos += 12 + length
        if kind == b"IHDR":
            w, h, depth, colour, _, _, interlace = struct.unpack(">IIBBBBB", body)
            if (depth, colour, interlace) != (8, 6, 0):
                sys.exit(f"{path}: needs 8-bit RGBA, not interlaced")
        elif kind == b"IDAT":
            idat += body
    raw, stride, prev, rows, at = zlib.decompress(idat), w * 4, bytearray(w * 4), [], 0
    for _ in range(h):
        kind, line = raw[at], bytearray(raw[at + 1:at + 1 + stride])
        at += 1 + stride
        for i in range(stride):
            a = line[i - 4] if i >= 4 else 0
            b = prev[i]
            c = prev[i - 4] if i >= 4 else 0
            if kind == 1:
                line[i] = (line[i] + a) & 255
            elif kind == 2:
                line[i] = (line[i] + b) & 255
            elif kind == 3:
                line[i] = (line[i] + (a + b) // 2) & 255
            elif kind == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append([tuple(line[x * 4:x * 4 + 4]) for x in range(w)])
        prev = line
    return w, h, rows


def main():
    out = [
        "/* Generated by tools/sprite_editor/gen_sprites.py from the PNGs in tools/sprite_editor/sprites: do not edit. */",
        "#ifndef CTR_EDIT_SPRITES_H",
        "#define CTR_EDIT_SPRITES_H",
        "#include <stdint.h>",
        f"#define SPRITE_SIZE {SIZE}",
        "/* A clear pixel. */",
        f"#define SPRITE_CLEAR 0x{CLEAR:04X}",
        "enum { " + ", ".join(name for name, _ in SPRITES) + ", SPRITE_COUNT };",
        "/* RGB565, row by row. */",
        "static const uint16_t sSprites[SPRITE_COUNT][SPRITE_SIZE * SPRITE_SIZE] = {",
    ]
    for name, file in SPRITES:
        w, h, rows = load_png(os.path.join(HERE, "sprites", file + ".png"))
        if (w, h) != (SIZE, SIZE):
            sys.exit(f"{file}.png is {w}x{h}, not {SIZE}x{SIZE}")
        out.append(f"    {{ /* {file} */")
        for row in rows:
            cells = []
            for r, g, b, a in row:
                c = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) if a >= 128 else CLEAR
                if a >= 128 and c == CLEAR:
                    c ^= 0x20
                cells.append(f"0x{c:04X}")
            out.append("        " + ", ".join(cells) + ",")
        out.append("    },")
    out += ["};", "#endif", ""]
    open(OUT, "w").write("\n".join(out))
    print(OUT)


if __name__ == "__main__":
    main()
