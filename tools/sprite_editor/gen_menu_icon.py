#!/usr/bin/env python3
"""Generates 3ds_port/src/3ds_menu_icon.h: the bottom screen column's EDITOR button picture,
tools/sprite_editor/sprites/editor_menu.png (24x24, 8-bit RGBA; made with PixelLab).

    python3 tools/sprite_editor/gen_menu_icon.py

Each pixel becomes RGB565; a clear one (alpha under 128) becomes MENU_ICON_CLEAR.
Standard library only: reads the PNG with gen_sprites.py's loader.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_sprites  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "3ds_port", "src", "3ds_menu_icon.h")
CLEAR = gen_sprites.CLEAR


def main():
    w, h, rows = gen_sprites.load_png(os.path.join(HERE, "sprites", "editor_menu.png"))
    px = []
    for row in rows:
        for x in range(w):
            r, g, b, a = row[x]
            c = CLEAR if a < 128 else ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            if a >= 128 and c == CLEAR:
                c ^= 0x20
            px.append(c)
    lines = ["/* Generated by tools/sprite_editor/gen_menu_icon.py from sprites/editor_menu.png: do not edit. */",
             "#ifndef CTR_MENU_ICON_H", "#define CTR_MENU_ICON_H", "#include <stdint.h>",
             "#define MENU_ICON_W %d" % w, "#define MENU_ICON_H %d" % h, "#define MENU_ICON_CLEAR 0x%04X" % CLEAR,
             "/* RGB565, row by row. */", "static const uint16_t sMenuIcon[MENU_ICON_W * MENU_ICON_H] = {"]
    for y in range(h):
        lines.append("    " + ", ".join("0x%04X" % c for c in px[y * w:(y + 1) * w]) + ",")
    lines += ["};", "#endif", ""]
    open(OUT, "w").write("\n".join(lines))
    print("wrote", OUT, "%dx%d" % (w, h))


if __name__ == "__main__":
    main()
