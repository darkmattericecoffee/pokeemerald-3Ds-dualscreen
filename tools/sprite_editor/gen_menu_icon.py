#!/usr/bin/env python3
"""Generates 3ds_port/src/3ds_menu_icon.h: the bottom screen column's EDITOR button picture,
tools/sprite_editor/sprites/editor_menu.png (24x24, 8-bit RGBA; made with PixelLab), and the
plane editor's globe (online.png, 24x24: the server's new pictures).

    python3 tools/sprite_editor/gen_menu_icon.py

Each pixel becomes RGB565; a clear one (alpha under 128) becomes MENU_ICON_CLEAR.
Standard library only: reads the PNG with gen_sprites.py's loader.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_sprites  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "3ds_port", "src", "3ds_menu_icon.h")
CLEAR = gen_sprites.CLEAR


def pixels(name):
    w, h, rows = gen_sprites.load_png(os.path.join(HERE, "sprites", name))
    px = []
    for row in rows:
        for x in range(w):
            r, g, b, a = row[x]
            c = CLEAR if a < 128 else ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            if a >= 128 and c == CLEAR:
                c ^= 0x20
            px.append(c)
    return w, h, px


def table(lines, prefix, var, w, h, px):
    lines += ["#define %s_W %d" % (prefix, w), "#define %s_H %d" % (prefix, h),
              "/* RGB565, row by row. */", "static const uint16_t %s[%s_W * %s_H] __attribute__((unused)) = {" % (var, prefix, prefix)]
    for y in range(h):
        lines.append("    " + ", ".join("0x%04X" % c for c in px[y * w:(y + 1) * w]) + ",")
    lines.append("};")


def main():
    lines = ["/* Generated by tools/sprite_editor/gen_menu_icon.py from sprites/editor_menu.png and"
             " sprites/online.png: do not edit. */",
             "#ifndef CTR_MENU_ICON_H", "#define CTR_MENU_ICON_H", "#include <stdint.h>",
             "#define MENU_ICON_CLEAR 0x%04X" % CLEAR]
    table(lines, "MENU_ICON", "sMenuIcon", *pixels("editor_menu.png"))
    table(lines, "ONLINE_ICON", "sOnlineIcon", *pixels("online.png"))
    lines += ["#endif", ""]
    open(OUT, "w").write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
